def _schedule(path: Path) -> dict:
    if not path.exists():
        raise SystemExit(
            f"Missing schedule {path}. Run: .venv/bin/python experiments/run_deepprove_work.py "
            "--prepare --output-dir experiments/results/deepprove_work/audited"
        )
    return load_schedule(path)


def _write_json(path: Path, value: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, sort_keys=True) + "\n")


def _write_csv(path: Path, rows: Iterable[dict]) -> None:
    rows = list(rows)
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        path.write_text("")
        return
    keys = sorted({key for row in rows for key in row})
    with path.open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=keys)
        writer.writeheader()
        writer.writerows(rows)


def _write_report(path: Path, title: str, summary: dict, notes: list[str]) -> None:
    lines = [
        f"# {title}",
        "",
        "Generated by `experiments/run_llm_experiments.py`.",
        "",
        "## Summary",
        "",
    ]
    for key, value in summary.items():
        lines.append(
            f"- **{key}:** `{json.dumps(value, sort_keys=True) if isinstance(value, (dict, list)) else value}`"
        )
    lines.extend(["", "## Reproduction notes", ""])
    lines.extend(f"- {note}" for note in notes)
    path.write_text("\n".join(lines) + "\n")


def _quantiles(values: list[float]) -> dict[str, float]:
    if not values:
        return {
            "mean": math.nan,
            "stdev": math.nan,
            "p05": math.nan,
            "p50": math.nan,
            "p95": math.nan,
        }
    ordered = sorted(values)
    return {
        "mean": statistics.fmean(ordered),
        "stdev": statistics.stdev(ordered) if len(ordered) > 1 else 0.0,
        "p05": ordered[max(0, math.ceil(0.05 * len(ordered)) - 1)],
        "p50": ordered[max(0, math.ceil(0.50 * len(ordered)) - 1)],
        "p95": ordered[max(0, math.ceil(0.95 * len(ordered)) - 1)],
    }


def _plot_liveness(rows: list[dict], output: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    values = [float(row["block_time"]) for row in rows if row["adopted"]]
    if not values:
        return
    fig, axes = plt.subplots(1, 3, figsize=(13, 4))
    axes[0].hist(
        values, bins=min(30, max(5, len(values) // 5)), color="#3366aa", alpha=0.85
    )
    axes[0].set(
        xlabel="Block interval (s)", ylabel="Blocks", title="LLM PoML block intervals"
    )
    axes[1].plot(
        sorted(values),
        [i / len(values) for i in range(1, len(values) + 1)],
        color="#cc5500",
    )
    axes[1].set(
        xlabel="Block interval (s)", ylabel="Empirical CDF", title="Liveness CDF"
    )
    axes[2].boxplot(
        values,
        vert=True,
        patch_artist=True,
        boxprops={"facecolor": "#77aadd"},
        medianprops={"color": "#222222", "linewidth": 1.3},
        whiskerprops={"color": "#444444"},
        capprops={"color": "#444444"},
        flierprops={"marker": ".", "markersize": 3, "alpha": 0.35},
    )
    axes[2].axhline(300.0, color="#cc5500", linestyle="--", label="300 s target")
    axes[2].set(
        ylabel="Block interval (s)",
        title="Block-time box plot",
        xticks=[1],
        xticklabels=[f"{len(values)} blocks"],
    )
    axes[2].legend(frameon=False, loc="upper right")
    fig.tight_layout()
    output.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output, dpi=180)
    plt.close(fig)


def _plot_selection(records: list[dict], output: Path) -> None:
    """Plot attacker block share and completed-work share by policy."""
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    policies = SELECTION_POLICIES
    block = []
    work = []
    for policy in policies:
        selected = [row for row in records if row["strategy"] == policy]
        block.append(
            100 * statistics.fmean(row["attacker_block_share"] for row in selected)
        )
        work.append(
            100 * statistics.fmean(row["attacker_work_share"] for row in selected)
        )
    positions = list(range(len(policies)))
    fig, ax = plt.subplots(figsize=(7, 4))
    width = 0.38
    ax.bar([p - width / 2 for p in positions], block, width, label="Block share")
    ax.bar(
        [p + width / 2 for p in positions], work, width, label="Completed-work share"
    )
    ax.set_xticks(
        positions, ["Uniform", "Profiled\nshort", "Profiled\nlong", "Shortest\nprompt"]
    )
    ax.set_ylabel("Attacker share (%)")
    ax.set_title("Selection policy shares")
    ax.legend(frameon=False)
    fig.tight_layout()
    output.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output, dpi=180)
    plt.close(fig)


