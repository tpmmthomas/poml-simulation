    if args.command == "calibrate":
        return cmd_calibrate(args)
    if args.command == "liveness":
        return cmd_liveness(args)
    if args.command == "cherry-pick":
        return cmd_cherry_pick(args)
    if args.command == "settlement":
        return cmd_settlement(args)
    if args.command == "wasted-work":
        return cmd_wasted_work(args)
