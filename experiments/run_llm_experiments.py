def _make_pool(
    args: argparse.Namespace,
    schedule: dict,
    *,
    seed: int | None = None,
    count: int | None = None,
) -> list[QuerySpec]:
    metadata_path = getattr(args, "trace_pool_metadata", None)
    if metadata_path is not None:
        metadata = json.loads(Path(metadata_path).read_text())
        if metadata.get("schema") != BENCHMARK_SCHEMA:
            raise ValueError(
                "obsolete single-prompt/artificial-label bank; build benchmark traces"
            )
        records = metadata.get("pool")
        if not isinstance(records, list):
            raise SystemExit("trace pool metadata has no pool list")
        args.max_output = int(metadata["max_output"])
        if len({r["query_id"] for r in records}) != len(records) or len(
            {r["prompt_sha256"] for r in records}
        ) != len(records):
            raise ValueError(
                "benchmark pool must contain distinct prompt tokens and identifiers"
            )
        if any(
            r["profile_trials"] < 2
            or not 1 <= r["profile_mean_output_length"] <= r["max_output_length"]
            for r in records
        ):
            raise ValueError("missing or invalid measured output-length profiles")
        wanted = count or args.pool_size
        base = [
            QuerySpec(
                query_id=str(record["query_id"]),
                prompt_length=int(record["prompt_length"]),
                max_output_length=int(record["max_output_length"]),
                category="benchmark:wikitext2",
                fee_limit=float(record.get("fee_limit", 0.0)),
                profile_mean_output_length=float(record["profile_mean_output_length"]),
                profile_trials=int(record["profile_trials"]),
            )
            for record in records
        ]
        if wanted <= len(base):
            return base[:wanted]
        if args.command not in {"wasted-work", "settlement"}:
            raise ValueError(
                "Experiments 1–2 require distinct benchmark prompts; requested pool exceeds bank"
            )
        rng = random.Random(args.seed if seed is None else seed)
        # Scale request IDs, preserving each benchmark prompt's paired K,T bank.
        return [
            replace(q, query_id=f"request-{i:06d}", trace_query_id=q.query_id)
            for i, q in enumerate(rng.choices(base, k=wanted))
        ]
    if not getattr(args, "synthetic_smoke", False):
        raise ValueError(
            "paper experiments require --trace-pool-metadata; synthetic fixtures require --synthetic-smoke"
        )
    lengths = (
        (args.prompt_length,)
        if args.prompt_length is not None
        else (2, 4, 8, 16, 24, 32)
    )
    return make_query_pool(
        count or args.pool_size,
        seed=args.seed if seed is None else seed,
        schedule=schedule,
        max_output_length=args.max_output,
        prompt_lengths=lengths,
    )


def _load_trace_bank(args: argparse.Namespace, pool: list[QuerySpec]) -> dict | None:
    """Load traces and reject silent synthetic fallback in real campaigns."""

    benchmark = bool(getattr(args, "trace_pool_metadata", None))
    if benchmark:
        args.require_traces = True
        args.trace_duration = True
        if args.trace_file is None:
            raise ValueError("benchmark metadata requires --trace-file")
        metadata = json.loads(Path(args.trace_pool_metadata).read_text())
        if metadata.get("schema") != BENCHMARK_SCHEMA:
            raise ValueError("obsolete trace schema")
        if (
            hashlib.sha256(args.trace_file.read_bytes()).hexdigest()
            != metadata["trace_sha256"]
        ):
            raise ValueError("benchmark trace digest mismatch")
        if (
            hashlib.sha256(args.schedule.read_bytes()).hexdigest()
            != metadata["schedule_sha256"]
        ):
            raise ValueError("benchmark schedule digest mismatch")
        proof_ids = set()
        benchmark_queries = {r["query_id"]: r for r in metadata["pool"]}
        for line in args.trace_file.read_text().splitlines():
            row = json.loads(line)
            if row.get("phase") != "evaluation":
                raise ValueError(
                    "profiling outcomes cannot enter the mining trace bank"
                )
            record = benchmark_queries[row["query_id"]]
            if (
                row["prompt_sha256"] != record["prompt_sha256"]
                or row["prompt_length"] != record["prompt_length"]
            ):
                raise ValueError("evaluation trace differs from benchmark prompt")
            identity = (row["proof_directory"], row["proof_trial"])
            if identity in proof_ids:
                raise ValueError("a proof timing was reused across evaluation trials")
            proof_ids.add(identity)
        if (
            metadata.get("proof_timing_reuse") is not False
            or len(proof_ids) != metadata["proof_measurements"]
        ):
            raise ValueError("benchmark requires one proof timing per evaluation trial")
    trace_bank = trace_from_jsonl(args.trace_file) if args.trace_file else None
    if benchmark:
        trace_bank = {
            key: value
            for key, value in trace_bank.items()
            if not key.startswith("shape:")
        }
    if args.require_traces:
        if trace_bank is None:
            raise SystemExit("--require-traces requires --trace-file")
        metadata_path = args.trace_file.with_suffix(".metadata.json")
        if args.trace_duration:
            if not metadata_path.exists():
                raise SystemExit(
                    f"measured trace mode requires provenance metadata at {metadata_path}"
                )
            metadata = json.loads(metadata_path.read_text())
            scope = str(metadata.get("duration_scope", ""))
            if "DeepProve" not in scope or metadata.get("backend") != "cuda":
                raise SystemExit(
                    "--trace-duration requires a CUDA GPT-2+DeepProve trace bank"
                )
        missing = [
            query.query_id
            for query in pool
            if (query.trace_query_id or query.query_id) not in trace_bank
            and f"shape:{query.prompt_length}" not in trace_bank
        ]
        if missing:
            preview = ", ".join(missing[:5])
            raise SystemExit(
                f"trace file is missing {len(missing)} query IDs (for example {preview})"
            )
    return trace_bank


def _ticket_rate(args: argparse.Namespace, trace_bank: dict | None) -> float:
    """Return virtual tickets per second for difficulty calibration."""

    if not args.trace_duration or trace_bank is None:
        return args.work_rate
    traces = [
        trace
        for key, traces in trace_bank.items()
        if not key.startswith("shape:")
        for trace in traces
    ]
    if not traces:
        traces = [trace for traces in trace_bank.values() for trace in traces]
    if not traces:
        raise SystemExit("real trace file contains no usable durations")
    # Serial throughput is E[C]/E[T], not E[C/T].
    return sum(t.complexity for t in traces) / sum(t.duration for t in traces)


def _trace_distribution(trace_bank: dict | None) -> list:
    """Return measured traces once per real query, excluding shape aliases."""
    if trace_bank is None:
        return []
    return [
        trace
        for key, traces in trace_bank.items()
        if not key.startswith("shape:")
        for trace in traces
    ]


def _empirical_trace_bank(pool: list[QuerySpec], traces: list, schedule: dict) -> dict:
    """Cache C(N,K) without changing empirical draws, order, or multiplicity.

    This preserves the existing Experiment 3 pooled-duration model exactly:
    each template supplies K and duration, while the query supplies N. It does
    not turn the pooled timings into measurements of every simulated (N,K).
    """
    representatives = {query.prompt_length: query for query in pool}
    bank = {}
    for length, query in representatives.items():
        costs = {
            k: complexity_for(query, k, schedule)
            for k in {trace.output_length for trace in traces}
        }
        bank[f"shape:{length}"] = tuple(
            QueryTrace(trace.output_length, costs[trace.output_length], trace.duration)
            for trace in traces
        )
    return bank


def _difficulty(args: argparse.Namespace, trace_bank: dict | None) -> float:
    """Calibrate per-ticket success probability from synthetic or real rates."""

    rate = _ticket_rate(args, trace_bank)
    return -math.expm1(-1.0 / (args.miners * rate * args.target))


def cmd_calibrate(args: argparse.Namespace) -> int:
    schedule = _schedule(args.schedule)
    pool = _make_pool(args, schedule)
    trace_bank = _load_trace_bank(args, pool)
    empirical = _trace_distribution(trace_bank)
    expected = (
        statistics.fmean(t.complexity for t in empirical)
        if empirical
        else statistics.fmean(
            complexity_for(q, max(1, q.max_output_length // 2), schedule) for q in pool
        )
    )
    per_miner_rate = _ticket_rate(args, trace_bank)
    ticket_rate = args.miners * per_miner_rate
    probability = _difficulty(args, trace_bank)
    difficulty = math.floor(probability * (1 << 256))
    output = (args.output or DEFAULT_OUTPUT / "calibration.json").resolve()
    result = {
        "schema": "poml-llm-calibration-1",
        "seed": args.seed,
        "schedule": str(args.schedule.resolve()),
        "schedule_sha256": hashlib.sha256(args.schedule.read_bytes()).hexdigest(),
        "miners": args.miners,
        "work_rate_complexity_units_per_second": args.work_rate,
        "measured_trace_ticket_rate": per_miner_rate if args.trace_duration else None,
        "target_block_time_seconds": args.target,
        "mean_expected_complexity": expected,
        "aggregate_ticket_rate": ticket_rate,
        "per_virtual_ticket_success_probability": probability,
        "difficulty_hex": hex(difficulty),
        "pool_size": args.pool_size,
        "max_output_length": args.max_output,
        "model": "GPT-2/DeepProve reference operation schedule",
    }
    _write_json(output, result)
    print(json.dumps(result, indent=2))
    return 0


def _run_races(
    args: argparse.Namespace,
    schedule: dict,
    pool: list[QuerySpec],
    *,
    strategies: tuple[str, ...] | None = None,
    response_probability: float = 0.0,
    trace_bank: dict | None = None,
    trace_distribution: list | None = None,
    retain_results: bool = True,
) -> tuple[list[dict], list]:
    rows: list[dict] = []
    results = []
    p = args.difficulty_probability
    trial_count = getattr(args, "blocks", getattr(args, "races", None))
    if trial_count is None:
        raise ValueError("runner arguments must define blocks or races")
    unit = "block" if hasattr(args, "blocks") else "race"
    for race in tqdm(
        range(trial_count),
        desc=args.progress,
        unit=unit,
        disable=getattr(args, "quiet", False),
    ):
        result = simulate_race(
            pool,
            miner_count=args.miners,
            work_rates=(args.work_rate,) * args.miners,
            difficulty_probability=p,
            seed=args.seed + race,
            schedule=schedule,
            strategies=strategies,
            response_inclusion_probability=response_probability,
            trace_bank=trace_bank,
            trace_duration=args.trace_duration,
            require_trace_bank=args.require_traces,
            trace_distribution=trace_distribution,
            max_events=getattr(args, "max_events", 100_000),
            replenish_pool=args.command in {"liveness", "cherry-pick"},
        )
        if retain_results:
            results.append(result)
        rows.append(
            {
                ("block" if hasattr(args, "blocks") else "race"): race,
                "seed": args.seed + race,
                "adopted": int(result.adopted),
                "termination_reason": result.termination_reason,
                "winner": "" if result.winner is None else result.winner,
                "block_time": result.block_time,
                "winning_complexity": result.winning_complexity,
                "successful_pair_complexity": sum(
                    a.trace.complexity for a in result.attempts if a.won
                ),
                "canonical_queries": sum(
                    result.adopted and a.miner_id == result.winner
                    for a in result.attempts
                ),
                "total_completed_complexity": result.total_completed_complexity,
                "settled_complexity": result.settled_complexity,
                "discarded_complexity": result.discarded_complexity,
                "unfinished_complexity": result.unfinished_complexity,
                "settled_queries": result.settled_queries,
                "attempts": len(result.attempts),
                "unique_queries_completed": len({a.query_id for a in result.attempts}),
            }
        )
        audit_limit = getattr(args, "audit_event_limit", None)
        if audit_limit is not None:
            # Reconstruct the archived capped/no-response accounting from the
            # same event prefix while allowing this run to finish naturally.
            legacy_adopted = result.adopted and len(result.attempts) <= audit_limit
            prefix_total = sum(
                a.trace.complexity for a in result.attempts[:audit_limit]
            )
            rows[-1].update(
                legacy_adopted=int(legacy_adopted),
                legacy_total_completed_complexity=prefix_total,
                legacy_unfinished_complexity=result.unfinished_complexity
                if legacy_adopted
                else 0,
                legacy_wasted_work_pct=(
                    100
                    * (
                        prefix_total
                        - sum(a.trace.complexity for a in result.attempts if a.won)
                    )
                    / prefix_total
                    if legacy_adopted
                    else math.nan
                ),
                previously_event_limited=int(len(result.attempts) > audit_limit),
            )
    return rows, results


def _base_manifest(
    args: argparse.Namespace,
    schedule_path: Path,
    pool: list[QuerySpec],
    config: SimulationConfig,
) -> dict:
    data = manifest(config, schedule_path=schedule_path, pool=pool)
    data["cli"] = {
        key: str(value) if isinstance(value, Path) else value
        for key, value in vars(args).items()
    }
    data["schedule"] = str(schedule_path.resolve())
    data["source_sha256"] = {
        str(path.relative_to(ROOT)): hashlib.sha256(path.read_bytes()).hexdigest()
        for path in (
            Path(__file__),
            ROOT / "src/poml_sim/llm_simulation.py",
            ROOT / "src/poml_sim/llm_benchmark.py",
            ROOT / "src/poml_sim/gpt2_work.py",
        )
    }
    if args.trace_pool_metadata:
        data["benchmark_metadata_sha256"] = hashlib.sha256(
            args.trace_pool_metadata.read_bytes()
        ).hexdigest()
    return data


def cmd_liveness(args: argparse.Namespace) -> int:
    output = (args.output or DEFAULT_OUTPUT / "liveness").resolve()
    if output.exists() and any(output.iterdir()):
        raise FileExistsError(f"refusing nonempty liveness output {output}")
    schedule = _schedule(args.schedule)
    pool = _make_pool(args, schedule)
    trace_bank = _load_trace_bank(args, pool)
    calibration = _difficulty(args, trace_bank)
    args.difficulty_probability = calibration
    args.progress = "Experiment 1 liveness"
    args.max_events = None
    rows, results = _run_races(args, schedule, pool, trace_bank=trace_bank)
    output = (args.output or DEFAULT_OUTPUT / "liveness").resolve()
    output.mkdir(parents=True, exist_ok=True)
    _write_csv(output / "blocks.csv", rows)
    adopted = [row["block_time"] for row in rows if row["adopted"]]
    summary = {
        "experiment": "honest_llm_liveness",
        "blocks": args.blocks,
        "adopted_blocks": len(adopted),
        "adoption_rate": len(adopted) / max(1, len(rows)),
        "timeout_probability": 1.0 - len(adopted) / max(1, len(rows)),
        "block_time_seconds": _quantiles(adopted),
        "mean_attempts": statistics.fmean(row["attempts"] for row in rows),
        "mean_completed_complexity": statistics.fmean(
            row["total_completed_complexity"] for row in rows
        ),
        "mean_unfinished_complexity": statistics.fmean(
            row["unfinished_complexity"] for row in rows
        ),
        "difficulty_probability": calibration,
        "target_block_time": args.target,
    }
    _write_json(output / "summary.json", summary)
    _write_csv(output / "query_pool.csv", _pool_rows(pool, schedule))
    _write_json(
        output / "manifest.json",
        _base_manifest(
            args,
            args.schedule,
            pool,
            SimulationConfig(
                seed=args.seed,
                miner_count=args.miners,
                difficulty_probability=calibration,
                target_block_time=args.target,
                miner_work_rates=(args.work_rate,) * args.miners,
            ),
        ),
    )
    _plot_liveness(rows, output / "block_times.png")
    _write_report(
        output / "report.md",
        "Experiment 1: Honest LLM liveness",
        summary,
        [
            "The query pool is continuously available; K is sampled only when a miner executes a query.",
            "The chain is simulated until the requested number of blocks is adopted; each block is one independent race in the accelerated model.",
            "Each completed query contributes C(N,K) independent virtual tickets.",
            "See manifest.json for the schedule digest, seed, grid, and full query metadata.",
        ],
    )
    print(json.dumps(summary, indent=2))
    (output / "COMPLETED").write_text("benchmark liveness complete\n")
    return 0


def _selection_profiles(args: argparse.Namespace, pool: list[QuerySpec]) -> dict:
    """Recompute frozen profiles and reject leakage or altered metadata."""
    if args.trace_pool_metadata is None or args.synthetic_smoke:
        raise ValueError(
            "Experiment 2 requires real benchmark profiles and held-out evaluation traces"
        )
    directory = args.trace_file.parent
    metadata = json.loads(args.trace_pool_metadata.read_text())
    phases = {}
    for phase, digest_key in (
        ("profile", "profile_sha256"),
        ("evaluation", "evaluation_sha256"),
    ):
        path = directory / f"{phase}_rollouts.jsonl"
        if hashlib.sha256(path.read_bytes()).hexdigest() != metadata[digest_key]:
            raise ValueError(f"{phase} rollout digest mismatch")
        phases[phase] = [
            json.loads(line) for line in path.read_text().splitlines() if line.strip()
        ]
    prompts = json.loads((directory / "prompts.json").read_text())["prompts"]
    frozen = profile_pool(prompts, phases["profile"])
    by_id = {r["query_id"]: r for r in frozen}
    for query in pool:
        record = by_id[query.query_id]
        if (
            query.profile_mean_output_length != record["profile_mean_output_length"]
            or query.profile_trials != record["profile_trials"]
        ):
            raise ValueError(
                "selection profile differs from profiling-only observations"
            )
    wanted = {q.query_id for q in pool}
    return prediction_diagnostics(
        [r for r in frozen if r["query_id"] in wanted],
        [r for r in phases["profile"] if r["query_id"] in wanted],
        [r for r in phases["evaluation"] if r["query_id"] in wanted],
    )


def _bootstrap_mean_interval(values: list[float]) -> list[float] | None:
    """Seed-group percentile interval conditional on the fixed benchmark bank."""
    import numpy as np

    if len(values) < 2 or not all(math.isfinite(v) for v in values):
        return None
    data = np.asarray(values)
    indices = np.random.default_rng(20260915).integers(
        0, len(data), size=(10000, len(data))
    )
    return np.quantile(data[indices].mean(axis=1), [0.025, 0.975]).tolist()


